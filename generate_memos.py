def gen_person():
    female = random.random() < 0.5
    first = random.choice(FEMALE_FIRST if female else MALE_FIRST)
    last = random.choice(FEMALE_LAST if female else LAST_NAMES)
    if first == "Анна" and last in (n for n in FEMALE_LAST):
        pass
    # падеж ФИО для получателя (дательный)
    return first, last, female


def dative(first, last, female):
    """ФИО в дательном падеже (для поля 'Кому')."""
    if not female:
        first = first.rstrip("й") + "ю" if first.endswith("й") else first + "у"
        last = last + "у"
    else:
        first = first
        last = last + "ой" if last.endswith("а") else last
    return f"{last} {first}"


