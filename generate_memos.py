def gen_body_paras(topic, first_phrase, min_len, max_len=1000):
    """Возвращает список абзацев, раскрывающих тему, суммарной длиной min_len..max_len.

    Тело строится из тематических блоков TOPIC_BODY_PARTS[topic] и перемежается
    общими связками GENERIC_BODY_PARTS, поэтому содержание соответствует теме
    (и, как следствие, названию файла).
    """
    topic_blocks = TOPIC_BODY_PARTS.get(topic, GENERIC_BODY_PARTS)
    best = None
    for _ in range(2000):
        n_paras = random.randint(2, 5)
        paras = []
        for _ in range(n_paras):
            pool = topic_blocks if random.random() < 0.7 else GENERIC_BODY_PARTS
            paras.append(" ".join(random.sample(pool, random.randint(1, 2))))

        total = sum(len(p) for p in paras)

        # добрать текст, пока не достигнут нижний порог
        attempts = 0
        while total < min_len and attempts < 200:
            idx = random.randrange(len(paras))
            pool = topic_blocks if random.random() < 0.7 else GENERIC_BODY_PARTS
            add = random.choice(pool)
            paras[idx] = paras[idx].rstrip() + " " + add
            total = sum(len(p) for p in paras)
            attempts += 1

        if total > max_len:
            continue

        paras = [p.strip() for p in paras]
        paras = [p if p.endswith(".") else p + "." for p in paras]
        paras[0] = first_phrase
        total = sum(len(p) for p in paras)
        if best is None or (min_len <= total <= max_len):
            best = paras
        if min_len <= total <= max_len:
            return paras
    if best:
        return best
    raise RuntimeError("Не удалось сгенерировать текст нужной длины")


def fill_template(word, data, out_path):
    doc = word.Documents.Open(TEMPLATE)
    try:
        for key, value in data.items():
            # тело обрабатываем отдельно (много абзацев + отступы)
            if key == "body":
                rng = doc.Content
                find = rng.Find
                find.ClearFormatting()
                find.Replacement.ClearFormatting()
                find.Text = "{{ body }}"
                if find.Execute(Replace=0):
                    full = "\r".join(value)  # \r = знак абзаца Word
                    rng.Text = full
                    rng.Font.Name = "Times New Roman"
                    rng.Font.Size = 12
                    rng.ParagraphFormat.FirstLineIndent = 35.4  # 1.25 см
                continue

            # поля ищем и в основном тексте, и в колонтитулах (футер: исполнитель/телефон)
            ranges = [doc.Content]
            for si in range(1, doc.Sections.Count + 1):
                sec = doc.Sections(si)
                ranges.append(sec.Headers(1).Range)
                ranges.append(sec.Footers(1).Range)

            for rng in ranges:
                if "{{" not in rng.Text:
                    continue
                for variant in ("{{ " + key + " }}", "{{" + key + "}}",
                                "{{ " + key + "}}", "{{" + key + " }}"):
                    if variant not in rng.Text:
                        continue
                    find = rng.Find
                    find.ClearFormatting()
                    find.Replacement.ClearFormatting()
                    # параметры Execute передаются позиционно (COM): ReplaceWith=value, Replace=wdReplaceOne
                    find.Execute(variant, 0, 0, 0, 0, 0, 0, 1, 0, value, 1)
        doc.SaveAs2(out_path, FileFormat=12)  # wdFormatXMLDocument (.docx)
        doc.Close(SaveChanges=False)
    except Exception:
        doc.Close(SaveChanges=False)
        raise


